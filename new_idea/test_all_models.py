def load_base_model(num_labels):
    tokenizer = AutoTokenizer.from_pretrained(CACHE_DIR)
    model = AutoModelForSequenceClassification.from_pretrained(CACHE_DIR, num_labels=num_labels)
    model.eval()
    return model, tokenizer


def load_lora_model(model_path, num_labels):
    tokenizer = AutoTokenizer.from_pretrained(CACHE_DIR)
    base_model = AutoModelForSequenceClassification.from_pretrained(CACHE_DIR, num_labels=num_labels)
    model = PeftModel.from_pretrained(base_model, model_path)
    model.eval()
    return model, tokenizer


def predict(text, model, tokenizer, labels, num_model_labels):
    inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=128)
    with torch.no_grad():
        outputs = model(**inputs)
        probs = torch.softmax(outputs.logits, dim=-1)
        
        # 三分类模型: [差评, 中评, 好评], 二分类: [差评, 好评]
        # 只取差评和好评的概率
        if num_model_labels == 3:
            # 映射: 0->差评, 2->好评
            neg_prob = probs[0][0].item()
            pos_prob = probs[0][2].item()
            pred = 0 if neg_prob > pos_prob else 1
        else:
            pred = torch.argmax(probs, dim=-1).item()
    
    # 返回二分类标签
    label_map = {0: "差评", 1: "好评"}
    return label_map[pred], probs[0][pred].item(), {"差评": probs[0][0].item(), "好评": probs[0][1].item() if num_model_labels == 2 else probs[0][2].item()}


def test_category(cat_key, cat_info):
    print(f"\n{'='*60}")
    print(f"【{cat_info['name']}】")
    print(f"{'='*60}")
    
    # electronics使用三分类模型，但测试用二分类标签
    if cat_info["num_labels"] == 3:
        model_path = f"{OUTPUT_DIR_3CLS}/{cat_info['path']}"
        # 预测时用二分类，但模型是三分类
        test_labels = BINARY_LABELS
    else:
        model_path = f"{OUTPUT_DIR}/{cat_info['path']}"
        test_labels = cat_info["labels"]
    
    if not os.path.exists(model_path):
        print(f"模型不存在: {model_path}")
        return
    
    try:
        base_model, tokenizer = load_base_model(num_labels=cat_info["num_labels"])
        lora_model, _ = load_lora_model(model_path, num_labels=cat_info["num_labels"])
    except Exception as e:
        print(f"加载模型失败: {e}")
        return
    
    labels = cat_info["labels"]
    samples = TEST_SAMPLES.get(cat_key, {})
    num_labels = cat_info["num_labels"]
    
    # 统计
    results = {"好评": {"correct": 0, "total": 0}, "差评": {"correct": 0, "total": 0}, "中评": {"倾向好评": 0, "倾向差评": 0, "total": 0}}
    
    for category, texts in samples.items():
        print(f"\n--- {category} ---")
        for text in texts:
            base_pred, base_conf, base_probs = predict(text, base_model, tokenizer, labels, num_labels)
            lora_pred, lora_conf, lora_probs = predict(text, lora_model, tokenizer, labels, num_labels)
            
            # 截断显示
            display_text = text[:30] + "..." if len(text) > 30 else text
            print(f"{display_text:<35}")
            print(f"  LoRA前: {base_pred}({base_conf:.0%}) 差评:{base_probs['差评']:.0%} 好评:{base_probs['好评']:.0%}")
            print(f"  LoRA后: {lora_pred}({lora_conf:.0%}) 差评:{lora_probs['差评']:.0%} 好评:{lora_probs['好评']:.0%}")
            
            # 统计
            if category == "好评":
                results["好评"]["total"] += 1
                if lora_pred == "好评":
                    results["好评"]["correct"] += 1
            elif category == "差评":
                results["差评"]["total"] += 1
                if lora_pred == "差评":
                    results["差评"]["correct"] += 1
            elif category == "中评":
                results["中评"]["total"] += 1
                if lora_pred == "好评":
                    results["中评"]["倾向好评"] += 1
                else:
                    results["中评"]["倾向差评"] += 1
    
    # 输出统计
    print(f"\n--- 统计结果 ---")
    if results["好评"]["total"] > 0:
        print(f"好评准确率: {results['好评']['correct']}/{results['好评']['total']} = {results['好评']['correct']/results['好评']['total']:.0%}")
    if results["差评"]["total"] > 0:
        print(f"差评准确率: {results['差评']['correct']}/{results['差评']['total']} = {results['差评']['correct']/results['差评']['total']:.0%}")
    if results["中评"]["total"] > 0:
        print(f"中评识别: 倾向好评{results['中评']['倾向好评']}, 倾向差评{results['中评']['倾向差评']}")


